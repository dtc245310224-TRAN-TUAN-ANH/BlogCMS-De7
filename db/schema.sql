USE blogcms;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(190) UNIQUE NOT NULL,
 password_hash VARCHAR(200) NOT NULL, role ENUM('admin','editor') NOT NULL DEFAULT 'editor',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) UNIQUE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS posts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL,slug VARCHAR(190) UNIQUE NOT NULL,
 excerpt VARCHAR(500) NOT NULL,content MEDIUMTEXT NOT NULL,
 category_id INT UNSIGNED NOT NULL, author_id INT UNSIGNED NOT NULL,
 status ENUM('draft','published') NOT NULL DEFAULT 'draft',
 source_url VARCHAR(1000) NOT NULL DEFAULT '',
 published_at TIMESTAMP NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE RESTRICT,
 FOREIGN KEY(author_id) REFERENCES users(id) ON DELETE RESTRICT,
 INDEX idx_public(status,published_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 sid VARCHAR(128) PRIMARY KEY, data JSON NOT NULL, expires BIGINT NOT NULL,
 INDEX idx_expiry(expires)
) ENGINE=InnoDB;
